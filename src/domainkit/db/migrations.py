ENV_DIR: Final = Path(__file__).with_name("migration_env")
_DATABASE: Final = "database"
_TARGET: Final = "target"


class DatabaseUnreachable(DomainkitError):
    """No connection to a database could be opened: down, unknown, or refused.

    The message names the database's driver, host, port, and name, never
    its credentials, and the driver's reason; the commands that migrate
    report it on one line, without a traceback.
    """


def where(url: URL) -> str:
    """The driver, host, port, and database of ``url``: nothing that logs in.

    The user, the password, and the query (``?password=`` is a credential to
    asyncpg) are left out. A host that holds an ``@`` holds the end of a
    password whose ``@`` was not encoded: it is not shown either.
    """
    host = url.host
    if host is not None and "@" in host:
        host = "***"  # The password's tail, then the host.
    shown = URL.create(url.drivername, host=host, port=url.port, database=url.database)
    hint = " (encode an @ in the password as %40)" if host == "***" else ""
    return shown.render_as_string() + hint  # It holds no password to hide.


@asynccontextmanager
async def _connected(
    engine: AsyncEngine, *, begin: bool = False
) -> AsyncIterator[AsyncConnection]:
    """A connection of ``engine``, in a transaction if ``begin``.

    Raises:
        DatabaseUnreachable: Opening it failed: the network refused, the
            host is unknown, the server turned the login away, or a SQLite
            file cannot be opened. Errors once connected pass unchanged.
    """
    async with AsyncExitStack() as stack:
        try:
            connection = await stack.enter_async_context(
                engine.begin() if begin else engine.connect()
            )
        except (OSError, DBAPIError) as exc:
            reason: BaseException = exc
            if isinstance(exc, DBAPIError) and exc.orig is not None:
                reason = exc.orig.__cause__ or exc.orig  # The driver's own.
            said = f"{type(reason).__name__}: {reason}" if str(reason) else ""
            raise DatabaseUnreachable(
                f"cannot be reached at {where(engine.url)} "
                f"({said or type(reason).__name__})"
            ) from exc
        yield connection


def versions_dir(target: str) -> Path:
    """The revision directory of ``target``."""
    if target == DEFAULT_DB_ALIAS:
        return settings.MIGRATIONS_DIR
    return settings.MIGRATIONS_DIR / target


def migration_targets() -> tuple[str, ...]:
    """Every target that holds tables of an installed app, ``default`` first."""
    return router.migration_targets()


def alembic_config(
    database: str = DEFAULT_DB_ALIAS, *, output: TextIO | None = None
) -> Config:
    """Build the Alembic configuration for an alias or a target.

    A shard group's revisions are read and written against its first
    database; they are the same in every database of the group. Offline
    SQL (``sql=True``) is written to ``output``, default stdout.
    """
    target = router.target_of_alias(database)
    alias = router.aliases_of(database)[0]
    versions = versions_dir(target)
    # Alembic's default stdout is bound when Alembic is imported; pass the
    # current one, or messages go to a stream that may be closed by now.
    config = Config(stdout=sys.stdout, output_buffer=output)
    options = {
        "script_location": str(ENV_DIR),
        "version_locations": str(versions),
        "path_separator": "os",
        "file_template": "%(rev)s_%(slug)s",
    }
    for key, value in options.items():
        # ConfigParser interpolation treats "%" as special.
        config.set_main_option(key, value.replace("%", "%%"))
    config.attributes[_DATABASE] = alias
    config.attributes[_TARGET] = target
    return config


@dataclass(frozen=True, slots=True)
class RevisionStatus:
    """One revision and whether the database has it."""

    revision: str
    message: str
    applied: bool


def next_revision_id(config: Config) -> str:
    """Return the next id: the highest sequence number plus one, and a suffix."""
    scripts = ScriptDirectory.from_config(config).walk_revisions()
    numbers = [_sequence_number(script.revision) for script in scripts]
    return f"{max(numbers, default=0) + 1:04d}_{secrets.token_hex(2)}"


def _sequence_number(revision: str) -> int:
    """Read the leading number of ``0002_a1b2`` (or of a plain ``0001``)."""
    number = revision.split("_", 1)[0]
    return int(number) if number.isdigit() else 0


def heads(database: str = DEFAULT_DB_ALIAS) -> list[str]:
    """Return the newest revision of every branch; more than one needs a merge."""
    return list(ScriptDirectory.from_config(alembic_config(database)).get_heads())


def make_merge(database: str = DEFAULT_DB_ALIAS) -> Path | None:
    """Join all heads in one merge revision; None when there is nothing to merge."""
    config = alembic_config(database)
    if len(ScriptDirectory.from_config(config).get_heads()) < 2:
        return None
    script = command.merge(
        config, revisions="heads", message="merge", rev_id=next_revision_id(config)
    )
    created = [Path(merged.path) for merged in (script,) if merged is not None]
    format_python(created)
    return created[0] if created else None


def status(database: str = DEFAULT_DB_ALIAS) -> list[RevisionStatus]:
    """List every revision, oldest first, marking those the database has."""
    config = alembic_config(_single_alias(database))
    scripts = ScriptDirectory.from_config(config)
    current = _run(_current_heads(connections.config(database)))
    applied = {script.revision for script in scripts.iterate_revisions(current, "base")}
    return [
        RevisionStatus(
            revision=script.revision,
            message=(script.doc or "").strip(),
            applied=script.revision in applied,
        )
        for script in reversed(list(scripts.walk_revisions()))
    ]


def check_message(message: str) -> None:
    """Refuse a revision message that would break out of the file's docstring.

    The message opens the revision's docstring, so it must be one line of
    printable text without backslashes or triple quotes.
    """
    if not message.isprintable() or "\\" in message or '"""' in message:
        raise ValueError(
            "A migration message is one line of text, without backslashes or "
            'triple quotes (""").'
        )


def make_migration(message: str, database: str = DEFAULT_DB_ALIAS) -> Path | None:
    """Autogenerate the next revision; return its path, or None if nothing changed."""
    check_message(message)
    config = alembic_config(database)
    # Only writing needs the directory: Alembic skips a missing one when
    # reading, so check, showmigrations, and migrate never create it.
    versions_dir(config.attributes[_TARGET]).mkdir(parents=True, exist_ok=True)
    result = command.revision(
        config,
        message=message,
        autogenerate=True,
        rev_id=next_revision_id(config),
        process_revision_directives=_skip_empty,
    )
    scripts = result if isinstance(result, list) else [result]
    created = [Path(script.path) for script in scripts if script is not None]
    format_python(created)
    return created[0] if created else None


def make_empty_migration(message: str, database: str = DEFAULT_DB_ALIAS) -> Path:
    """Write an empty revision for a data migration; return its path.

    Its ``upgrade`` and ``downgrade`` do nothing until filled in.
    """
    check_message(message)
    config = alembic_config(database)
    versions_dir(config.attributes[_TARGET]).mkdir(parents=True, exist_ok=True)
    script = command.revision(config, message=message, rev_id=next_revision_id(config))
    created = Path(script.path)  # type: ignore[union-attr]
    format_python([created])
    return created


@dataclass(frozen=True, slots=True)
class PlannedStep:
    """A revision ``migrate`` would apply or revert."""

    revision: str
    message: str
    upgrade: bool


def plan(
    target: str, database: str = DEFAULT_DB_ALIAS, *, downgrade: bool = False
) -> list[PlannedStep]:
    """The revisions moving alias ``database`` to ``target`` would run, in order."""
    alias = _single_alias(database)
    scripts = ScriptDirectory.from_config(alembic_config(alias))
    current = _run(_current_heads(connections.config(alias))) or None
    if downgrade:
        steps = scripts.iterate_revisions(current, target, select_for_downgrade=True)
    else:
        steps = reversed(list(scripts.iterate_revisions(target, current)))
    return [
        PlannedStep(step.revision, (step.doc or "").strip(), not downgrade)
        for step in steps
    ]


def current_revision(database: str = DEFAULT_DB_ALIAS) -> str:
    """The one revision alias ``database`` is at; ``base`` when it has none.

    Raises:
        alembic.util.exc.CommandError: The database is at several heads.
    """
    heads = _run(_current_heads(connections.config(_single_alias(database))))
    if len(heads) > 1:
        raise AlembicCommandError(
            f"Database {database!r} is at {len(heads)} heads; migrate it first."
        )
    return heads[0] if heads else "base"


def sql(
    target: str,
    database: str = DEFAULT_DB_ALIAS,
    *,
    start: str | None = None,
    downgrade: bool = False,
    output: TextIO | None = None,
) -> None:
    """Write the SQL moving alias ``database`` from ``start`` to ``target``.

    Nothing runs: Alembic renders the statements offline, for a DBA to
    review or apply. ``start`` defaults to the revision the database is at.
    """
    alias = _single_alias(database)
    start = start or current_revision(alias)
    config = alembic_config(alias, output=output)
    if downgrade:
        command.downgrade(config, f"{start}:{target}", sql=True)
    else:
        command.upgrade(config, f"{start}:{target}", sql=True)


def fake(
    target: str, database: str = DEFAULT_DB_ALIAS, *, downgrade: bool = False
) -> None:
    """Record alias ``database`` as at ``target`` without running anything.

    For a schema made by other means (a restored dump, a change applied by
    hand). Moving down records the lower revision the same way.
    """
    alias = _single_alias(database)
    if downgrade and target != "base":
        current = current_revision(alias)
        scripts = ScriptDirectory.from_config(alembic_config(alias))
        below = {step.revision for step in scripts.iterate_revisions(current, "base")}
        if target not in below:
            raise AlembicCommandError(
                f"Revision {target!r} is not below the database's {current!r}."
            )
    command.stamp(alembic_config(alias), target, purge=True)


def create_partitions(database: str = DEFAULT_DB_ALIAS) -> list[str]:
    """Create the current and upcoming partitions in alias ``database``."""
    return _run(maintain(_single_alias(database)))


def run_migrated_hooks(database: str = DEFAULT_DB_ALIAS) -> None:
    """Run the ``on_migrated`` hooks (``domainkit.db.hooks``) for alias ``database``."""
    alias = _single_alias(database)
    _run(_migrated(connections.config(alias), alias))


async def _migrated(database: DatabaseConfig, alias: str) -> None:
    """Run the hooks in one transaction, as the schema owner."""
    engine = create_owner_engine(database)
    try:
        async with _connected(engine, begin=True) as connection:
            for hook in on_migrated:
                await hook.call(connection, alias)
    finally:
        await engine.dispose()


def upgrade(target: str = "head", database: str = DEFAULT_DB_ALIAS) -> None:
    """Apply revisions up to ``target`` on the alias ``database``."""
    command.upgrade(alembic_config(_single_alias(database)), target)


def downgrade(target: str, database: str = DEFAULT_DB_ALIAS) -> None:
    """Revert alias ``database`` down to ``target`` (``base`` reverts everything)."""
    command.downgrade(alembic_config(_single_alias(database)), target)


def _single_alias(database: str) -> str:
    """Refuse a shard group where one database is meant."""
    if router.is_shard_group(database):
        raise ImproperlyConfigured(
            f"{database!r} is a shard group; migrate each of its aliases."
        )
    return database


def pending_changes(database: str = DEFAULT_DB_ALIAS) -> str | None:
    """Describe model changes that have no revision yet, or return None."""
    try:
        command.check(alembic_config(database))
    except AutogenerateDiffsDetected as exc:
        return str(exc)
    return None


def render_item(
    type_: str,
    obj: Any,  # noqa: ANN401 - Alembic passes any schema item.
    autogen_context: AutogenContext,
) -> str | Literal[False]:
    """Render ``TypeDecorator`` columns as their generic storage type.

    Revisions then never import domain code, which keeps changing after the
    revision is written. A decorator around another (a value object of a
    value object, or of an amount) is followed down to what it stores.
    SQLAlchemy's own decorated types (``Interval``, ``PickleType``) keep
    their names: ``Interval`` is a native ``INTERVAL`` on PostgreSQL, not
    the ``DateTime`` it stores elsewhere. Returning False keeps Alembic's
    own rendering.
    """
    if type_ != "type" or not isinstance(obj, TypeDecorator):
        return False
    if _sqlalchemy_type(obj):
        return False
    impl = obj.impl_instance
    while isinstance(impl, TypeDecorator) and not _sqlalchemy_type(impl):
        impl = impl.impl_instance
    if not type(impl).__module__.startswith("sqlalchemy.sql."):
        return False
    return f"sa.{impl!r}"


def _sqlalchemy_type(type_: TypeDecorator[Any]) -> bool:
    """Whether ``type_`` is one of SQLAlchemy's own, rendered by its name."""
    return type(type_).__module__.startswith("sqlalchemy.")


def run_migrations() -> None:
    """Entry point of ``migration_env/env.py``: migrate the configured alias.

    In offline mode (``sql=True``) the statements are rendered for the
    alias's dialect, values inline, and nothing connects.
    """
    setup()
    database = connections.config(context.config.attributes[_DATABASE])
    if context.is_offline_mode():
        _render_offline(database)
        return
    _run(_migrate(database))


def _render_offline(database: DatabaseConfig) -> None:
    """Configure Alembic for SQL output in the database's dialect, and run it.

    Values are written into the statements (``literal_binds``): offline SQL
    has nothing to bind them to. The autogenerate options are not needed.
    """
    url = make_url((database.MIGRATION_URL or database.URL).get_secret_value())
    context.configure(dialect_name=url.get_backend_name(), literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()


def _run[T](coroutine: Coroutine[Any, Any, T]) -> T:
    """Run ``coroutine`` to completion, even when called from async code.

    Inside a running event loop it runs in a fresh loop on a worker thread,
    so ``call_command("migrate")`` works from tests and async commands.
    """
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        return asyncio.run(coroutine)
    with ThreadPoolExecutor(max_workers=1) as executor:
        return executor.submit(asyncio.run, coroutine).result()


async def _migrate(database: DatabaseConfig) -> None:
    """Run the migrations on one connection."""
    engine = create_owner_engine(database)
    try:
        async with _connected(engine) as connection:
            await connection.run_sync(_configure_and_run)
    finally:
        await engine.dispose()


async def _current_heads(database: DatabaseConfig) -> tuple[str, ...]:
    """Read the revisions the database is at."""
    engine = create_owner_engine(database)
    try:
        async with _connected(engine) as connection:
            return await connection.run_sync(
                lambda sync: MigrationContext.configure(sync).get_current_heads()
            )
    finally:
        await engine.dispose()


def include_object(
    obj: object,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: object,
    *,
    target: str = DEFAULT_DB_ALIAS,
    partitions: frozenset[str] = frozenset(),
) -> bool:
    """Compare only the tables that belong in ``target``.

    A table tagged ``info={"domain": label}`` belongs where that domain's
    app keeps its tables (``DomainConfig.databases``), and nowhere while the
    domain is not installed. Untagged tables belong to ``default``. Leftover
    tables of other targets or uninstalled apps are ignored, so routing or
    uninstalling never proposes a destructive drop. Partitions (``partitions``)
    are managed by ``manage.py partitions``, not by revisions.
    """
    if type_ != "table":
        return True
    if not reflected:
        return isinstance(obj, Table) and router.holds_table(obj, target)
    if name in partitions:
        return False
    known = metadata.tables.get(name or "")
    if known is None:
        return router.holds_tables(None, target)
    return router.holds_table(known, target)


@comparators.dispatch_for("table")
def _money_checks(
    autogen_context: AutogenContext,
    modify_table_ops: ModifyTableOps,
    schema: str | None,
    tname: str,
    conn_table: Table | None,
    metadata_table: Table | None,
) -> None:
    """Add the both-or-neither check of a money pair added to an existing table.

    Alembic compares no check constraints, so a nullable money field added
    later would get its two columns and not the check that keeps them a
    pair (SEC-14a-3). A pair's check names its field (``info``); when the
    database table lacks that field's amount column, the revision adds the
    columns and then the check (in batch mode on SQLite).
    """
    if conn_table is None or metadata_table is None:
        return
    for constraint in metadata_table.constraints:
        if not isinstance(constraint, CheckConstraint):
            continue
        name = constraint.info.get(CHECK)
        if name is not None and name not in conn_table.c:
            modify_table_ops.ops.append(
                CreateCheckConstraintOp.from_constraint(constraint)
            )


def _configure_and_run(connection: Connection) -> None:
    """Configure Alembic for ``connection`` and run the migrations."""
    partitions = existing_partitions(connection)
    if connection.in_transaction():
        # The lookup began a transaction; end it so Alembic's own transaction,
        # not this read, decides what commits.
        connection.commit()
    context.configure(
        connection=connection,
        target_metadata=metadata,
        render_as_batch=connection.dialect.name == "sqlite",
        render_item=render_item,
        include_object=partial(
            include_object,
            target=context.config.attributes[_TARGET],
            partitions=partitions,
        ),
    )
    with context.begin_transaction():
        context.run_migrations()


def _skip_empty(
    migration_context: MigrationContext,
    revision: object,
    directives: list[MigrationScript],
) -> None:
    """Drop the revision when autogenerate found no changes (Django's behavior)."""
    operations = directives[0].upgrade_ops
    if operations is not None and operations.is_empty():
        directives.clear()
