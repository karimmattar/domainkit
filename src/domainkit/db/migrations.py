"""Alembic migrations configured from settings (``makemigrations`` / ``migrate``).

The Alembic environment ships with the framework (``migration_env``); the
project keeps only its revision files, in ``settings.MIGRATIONS_DIR``. There
is no ``alembic.ini``.

Revision ids are a sequence number plus a random suffix (``0002_a1b2``): files
sort in order, and two branches that both add ``0002`` still get distinct
ids. Merging those branches leaves two heads; ``makemigrations --merge``
joins them and ``check`` refuses to pass until then.

Each target (a SQL alias, or a shard group) has its own history: ``default``
in ``MIGRATIONS_DIR``, any other in ``MIGRATIONS_DIR/<target>``. A target's
revisions hold only the tables routed to it (see ``domainkit.db.routing``),
and a shard group's revisions are applied to each of its databases.
"""

